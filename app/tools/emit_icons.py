#!/usr/bin/env python3
"""Generate PWA icons + src/pwa-assets.js from the APPROVED vector shape.

Uses GEO.vectors.ic_cap_filled (the decoded APK drawable already embedded in
app/assets/proto-data.js). No new icon shape is invented: the two pathData
subpaths are flattened and filled over the approved --primary colour.

Requires Pillow (this sandbox: /home/user/_work/ocr_venv/bin/python).
"""
from __future__ import annotations
import base64, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
APP = ROOT / 'app'
try:
    from PIL import Image, ImageDraw
except ImportError:
    sys.exit('Pillow is required: use /home/user/_work/ocr_venv/bin/python')

data = (APP / 'assets/proto-data.js').read_text(encoding='utf-8')
i = data.index('var GEO=')
geo, _ = json.JSONDecoder().raw_decode(data[i + len('var GEO='):])
paths = geo['vectors']['ic_cap_filled']['paths']

NUM = r'[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?'
TOK = re.compile(r'[A-Za-z]|' + NUM)


def flatten(d: str, n: int = 18):
    toks, idx = TOK.findall(d), 0
    cur, start, pts, subs, cmd = (0.0, 0.0), (0.0, 0.0), [], [], None

    def num():
        nonlocal idx
        v = float(toks[idx]); idx += 1; return v

    while idx < len(toks):
        t = toks[idx]
        if t.isalpha():
            cmd = t; idx += 1
            if cmd == 'Z':
                if pts: pts.append(pts[0]); subs.append(pts); pts = []
                cur = start
            continue
        if cmd in ('M', 'L'):
            x, y = num(), num()
            if cmd == 'M':
                if pts: subs.append(pts)
                pts, start = [(x, y)], (x, y); cmd = 'L'
            else: pts.append((x, y))
            cur = (x, y)
        elif cmd == 'H':
            cur = (num(), cur[1]); pts.append(cur)
        elif cmd == 'V':
            cur = (cur[0], num()); pts.append(cur)
        elif cmd == 'C':
            x1, y1, x2, y2, x3, y3 = num(), num(), num(), num(), num(), num()
            x0, y0 = cur
            for k in range(1, n + 1):
                t2, u = k / n, 1 - k / n
                pts.append((u**3 * x0 + 3 * u * u * t2 * x1 + 3 * u * t2 * t2 * x2 + t2**3 * x3,
                            u**3 * y0 + 3 * u * u * t2 * y1 + 3 * u * t2 * t2 * y2 + t2**3 * y3))
            cur = (x3, y3)
        else:
            num()
    if pts: subs.append(pts)
    return subs

subs = [s for p in paths for s in flatten(p['d'])]
assert len(subs) >= 2, len(subs)
PRIMARY = (0x7E, 0x4B, 0xDE, 255)   # --primary (approved token)
WHITE = (0xFF, 0xFF, 0xFF, 255)     # --card (approved token)

out = APP / 'assets/icons'; out.mkdir(parents=True, exist_ok=True)
for name, size, maskable in [('icon-192.png', 192, False), ('icon-512.png', 512, False),
                             ('maskable-512.png', 512, True)]:
    img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if maskable:
        d.rectangle([0, 0, size, size], fill=PRIMARY); pad = size * 0.24
    else:
        d.rounded_rectangle([0, 0, size - 1, size - 1], radius=int(size * 0.22), fill=PRIMARY)
        pad = size * 0.19
    scale = (size - 2 * pad) / 24.0
    for sub in subs:
        d.polygon([(pad + x * scale, pad + y * scale) for x, y in sub], fill=WHITE)
    img.save(out / name, 'PNG')
    print('wrote', (out / name).relative_to(ROOT), (out / name).stat().st_size, 'bytes')

icons = {p.name: base64.b64encode(p.read_bytes()).decode('ascii') for p in sorted(out.glob('*.png'))}
pwa = {
    'generated': True,
    'source': 'GEO.vectors.ic_cap_filled (approved v12.5-fa payload)',
    'icons': icons,
    'manifestB64': base64.b64encode((APP / 'assets/pwa/manifest.webmanifest').read_bytes()).decode('ascii'),
    'swB64': base64.b64encode((APP / 'assets/pwa/sw.js').read_bytes()).decode('ascii'),
}
js = ('/* GENERATED by tools/emit_icons.py — do not edit by hand. */\n'
      'export const PWA_ASSETS = ' + json.dumps(pwa, ensure_ascii=False, indent=2) + ';\n')
(APP / 'src/pwa-assets.js').write_text(js, encoding='utf-8')
print('wrote app/src/pwa-assets.js', len(js), 'chars')
