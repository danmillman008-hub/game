#!/usr/bin/env python3
"""Generate src/design-tokens.js from the APPROVED stylesheet (no invention).

Reads app/assets/proto.css (:root + body.night) and the decoded APK catalog
mimo-ui/CATALOGS/DESIGN_TOKENS.json. Emits a plain ES module so both the
multi-file app and the single-file export share the same token structure.
"""
from __future__ import annotations
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[2]
APP = ROOT / 'app'
css = (APP / 'assets/proto.css').read_text(encoding='utf-8')


def block(selector: str) -> dict[str, str]:
    m = re.search(re.escape(selector) + r'\s*\{(.*?)\}', css, re.S)
    if not m:
        raise SystemExit(f'missing {selector} in proto.css')
    return {k: v.strip() for k, v in re.findall(r'(--[\w-]+)\s*:\s*([^;]+);', m.group(1))}


day, night = block(':root'), block('body.night')
catalog = json.loads((ROOT / 'mimo-ui/CATALOGS/DESIGN_TOKENS.json').read_text(encoding='utf-8'))
counts = {k: len(v) for k, v in catalog.items() if isinstance(v, dict)}

groups = [
    ('رنگهای اصلی', ['--primary', '--primary-hi', '--progress', '--progress-bg', '--progress-weak', '--purple-light']),
    ('سطوح و کارتها', ['--bg', '--card', '--card-pressed', '--sheet', '--line', '--line2', '--code-bg']),
    ('متن و آیکون', ['--text', '--text-weak', '--icon', '--weak-icon', '--disabled']),
    ('بازخورد', ['--yellow', '--blue', '--green', '--error', '--success']),
]
seen = {n for _, names in groups for n in names}
rest = [k for k in day if k not in seen]
if rest:
    groups.append(('سایر توکنها', rest))

tokens = [{
    'name': name,
    'day': day.get(name, ''),
    'night': night.get(name, ''),
} for _, names in groups for name in names]

payload = {
    'generatedBy': 'app/tools/emit_design_tokens.py',
    'source': 'app/assets/proto.css (byte-identical copy of approved v12.5-fa <style>)',
    'catalog': 'mimo-ui/CATALOGS/DESIGN_TOKENS.json',
    'catalogCounts': counts,
    'count': len(tokens),
    'groups': [{'title': t, 'names': n} for t, n in groups],
    'tokens': tokens,
}
out = APP / 'src' / 'design-tokens.js'
out.write_text(
    '/* GENERATED by tools/emit_design_tokens.py — do not edit by hand. */\n'
    'export const DESIGN_TOKENS = ' + json.dumps(payload, ensure_ascii=False, indent=2) + ';\n',
    encoding='utf-8')
print('wrote', out.relative_to(ROOT), 'tokens=', len(tokens), 'catalog=', counts)
