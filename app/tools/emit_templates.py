#!/usr/bin/env python3
"""Single source of truth -> browser module. Emits app/src/templates.js."""
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]
exam = json.loads((ROOT / 'content/EXAM_TEMPLATE.json').read_text(encoding='utf-8'))
practice = json.loads((ROOT / 'content/PRACTICE_TEMPLATE.json').read_text(encoding='utf-8'))
out = ('/* GENERATED by tools/emit_templates.py — do not edit by hand. */\n'
       f'export const EXAM_TEMPLATE = {json.dumps(exam, ensure_ascii=False, indent=2)};\n\n'
       f'export const PRACTICE_TEMPLATE = {json.dumps(practice, ensure_ascii=False, indent=2)};\n')
(ROOT / 'src/templates.js').write_text(out, encoding='utf-8')
print('wrote app/src/templates.js', len(out), 'chars')
