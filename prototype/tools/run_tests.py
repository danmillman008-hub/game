"""Run the prototype test suite and write prototype/TEST_REPORT.md.

    python -m prototype.tools.run_tests

Exit code is 0 only if every test passed.
"""
from __future__ import annotations

import os
import platform
import sys
import time
import unittest
from datetime import datetime, timezone
from pathlib import Path

os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
os.environ.setdefault("SDL_AUDIODRIVER", "dummy")

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

MODULES = [
    "prototype.tests.test_components",
    "prototype.tests.test_movement",
    "prototype.tests.test_combat",
    "prototype.tests.test_flow",
    "prototype.tests.test_render",
    "prototype.tests.test_scripted_encounter",
    "prototype.tests.test_smoke",
    "prototype.tests.test_web_port",
]


_NOTES: list[str] = []


class _Tee:
    """Capture the tests' printed encounter summaries while still echoing them."""

    def __init__(self, stream):
        self.stream = stream

    def write(self, text):
        self.stream.write(text)
        if "[" in text and "]" in text:
            _NOTES.append(text)

    def flush(self):
        self.stream.flush()

    def __getattr__(self, name):
        return getattr(self.stream, name)


class Recorder(unittest.TextTestResult):
    def __init__(self, *a, **kw):
        super().__init__(*a, **kw)
        self.records = []
        self.stdout_notes = _NOTES

    def addSuccess(self, test):
        super().addSuccess(test)
        self.records.append((test.id(), "PASS", ""))

    def addFailure(self, test, err):
        super().addFailure(test, err)
        self.records.append((test.id(), "FAIL", self._short(err)))

    def addError(self, test, err):
        super().addError(test, err)
        self.records.append((test.id(), "ERROR", self._short(err)))

    def addSkip(self, test, reason):
        super().addSkip(test, reason)
        self.records.append((test.id(), "SKIP", reason))

    @staticmethod
    def _short(err):
        return f"{err[0].__name__}: {err[1]}".replace("\n", " ")[:200]


def main() -> int:
    loader = unittest.TestLoader()
    suite = unittest.TestSuite(loader.loadTestsFromName(m) for m in MODULES)
    tee = _Tee(sys.stdout)
    sys.stdout = tee          # tests print their encounter summaries to stdout
    try:
        runner = unittest.TextTestRunner(verbosity=2, resultclass=Recorder, stream=tee)
        t0 = time.perf_counter()
        result = runner.run(suite)
        elapsed = time.perf_counter() - t0
    finally:
        sys.stdout = tee.stream

    try:
        import pygame
        pygame_version = pygame.version.ver
    except Exception:  # pragma: no cover
        pygame_version = "not installed"

    counts = {}
    for _, status, _msg in result.records:
        counts[status] = counts.get(status, 0) + 1
    total = sum(counts.values())

    lines = [
        "# Prototype test report — Neon Alley",
        "",
        "Generated by `python -m prototype.tools.run_tests` (do not edit by hand).",
        "",
        f"- generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}",
        f"- python: {platform.python_version()}  ({platform.platform()})",
        f"- pygame: {pygame_version}",
        f"- SDL_VIDEODRIVER: {os.environ.get('SDL_VIDEODRIVER')}",
        f"- wall time: {elapsed:.2f} s",
        "",
        "## Summary",
        "",
        "| result | count |",
        "| --- | --- |",
    ]
    for key in ("PASS", "FAIL", "ERROR", "SKIP"):
        lines.append(f"| {key} | {counts.get(key, 0)} |")
    lines += [f"| **total** | **{total}** |", ""]

    lines += ["## Test results", "", "| # | test | result | detail |", "| --- | --- | --- | --- |"]
    for i, (name, status, msg) in enumerate(result.records, 1):
        lines.append(f"| {i} | `{name}` | {status} | {msg or ''} |")

    lines += ["", "## Scripted encounter output", "", "```"]
    for note in result.stdout_notes:
        lines += note.rstrip().splitlines()
    lines += ["```", ""]

    out = ROOT / "prototype" / "TEST_REPORT.md"
    out.write_text("\n".join(lines))
    print(f"\nwrote {out.relative_to(ROOT)}")
    print(f"{counts.get('PASS', 0)} passed, {counts.get('FAIL', 0)} failed, "
          f"{counts.get('ERROR', 0)} errors, {counts.get('SKIP', 0)} skipped")
    return 0 if result.wasSuccessful() else 1


if __name__ == "__main__":
    raise SystemExit(main())
